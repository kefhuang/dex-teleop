#!/usr/bin/env python3
"""Quick read-only diagnostic for shared Deoxys control.

This script checks whether the Deoxys Python interface can receive robot and
optional gripper state for one or two Franka arms. By default it only subscribes
through ``FrankaInterface`` and never calls ``control()``, ``preprocess()``, or
``gripper_control()``.

With ``--start-backend`` it starts the shared driver's bimanual backend via
``auto_scripts/auto_bimanual.sh`` before sampling, then kills the tmux session at
exit. The Python-side sampling remains read-only.
"""

from __future__ import annotations

import argparse
import os
import signal
import subprocess
import sys
import time
from pathlib import Path
from typing import Any, NamedTuple

import numpy as np


REPO_ROOT = Path(__file__).resolve().parents[1]
import deoxys

DEOXYS_ROOT = Path(deoxys.__file__).resolve().parents[1]
DEFAULT_CONFIGS = ["franka-two.yml", "franka-three.yml"]

# The vendored deoxys protos may be generated by an older system protoc than the
# Python protobuf wheel in the conda environment. This compatibility mode keeps
# the diagnostic importable without changing global package versions.
os.environ.setdefault("PROTOCOL_BUFFERS_PYTHON_IMPLEMENTATION", "python")


class BackendPlan(NamedTuple):
    command: list[str]
    cwd: Path
    session_name: str


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Read-only diagnostic for shared Deoxys bimanual state data.",
    )
    parser.add_argument(
        "--configs",
        nargs="+",
        default=DEFAULT_CONFIGS,
        help=(
            "Deoxys interface config file names or paths. Default: "
            "franka-two.yml franka-three.yml."
        ),
    )
    parser.add_argument(
        "--duration",
        type=float,
        default=8.0,
        help="Seconds to wait/sample robot state. Default: 8.0.",
    )
    parser.add_argument(
        "--interval",
        type=float,
        default=0.5,
        help="Seconds between status prints. Default: 0.5.",
    )
    parser.add_argument(
        "--start-backend",
        action="store_true",
        help=(
            "Start auto_scripts/auto_bimanual.sh before sampling and stop its "
            "tmux session afterward. Requires exactly two configs."
        ),
    )
    parser.add_argument(
        "--backend-wait",
        type=float,
        default=5.0,
        help="Seconds to wait after starting backend before sampling. Default: 5.0.",
    )
    parser.add_argument(
        "--no-gripper",
        action="store_true",
        help=(
            "Pass has_gripper=False to FrankaInterface. Note: the upstream "
            "FrankaInterface still opens gripper sockets during initialization."
        ),
    )
    parser.add_argument(
        "--tmux-session",
        default="bimanual",
        help="tmux session name used by auto_bimanual.sh. Default: bimanual.",
    )
    return parser.parse_args()


def resolve_config(config: str) -> Path:
    path = Path(config)
    if path.is_absolute() or path.parent != Path("."):
        return path
    return DEOXYS_ROOT / "config" / config


def config_arg_for_backend(config: str) -> str:
    path = Path(config)
    if path.is_absolute() or path.parent != Path("."):
        return str(path)
    return f"config/{config}"


def build_backend_plan(start_backend: bool, configs: list[str], session_name: str = "bimanual") -> BackendPlan | None:
    if not start_backend:
        return None
    if len(configs) != 2:
        raise ValueError("--start-backend requires exactly two configs for auto_bimanual.sh")
    return BackendPlan(
        command=[
            "bash",
            "auto_scripts/auto_bimanual.sh",
            config_arg_for_backend(configs[0]),
            config_arg_for_backend(configs[1]),
        ],
        cwd=DEOXYS_ROOT,
        session_name=session_name,
    )


def assert_read_only_interface_usage(robot_interface: Any) -> bool:
    """Install guards so this diagnostic fails if it accidentally controls robots."""

    def forbidden(*_args: Any, **_kwargs: Any) -> None:
        raise RuntimeError("Read-only diagnostic attempted to call a control method")

    for method_name in ("control", "preprocess", "gripper_control"):
        if hasattr(robot_interface, method_name):
            setattr(robot_interface, method_name, forbidden)
    return True


def import_franka_interface() -> type[Any]:
    from deoxys.franka_interface import FrankaInterface  # noqa: PLC0415

    return FrankaInterface


def start_backend(plan: BackendPlan | None) -> subprocess.Popen[str] | None:
    if plan is None:
        return None
    if not (plan.cwd / "auto_scripts" / "auto_bimanual.sh").exists():
        raise FileNotFoundError(f"Missing backend script: {plan.cwd / 'auto_scripts' / 'auto_bimanual.sh'}")

    env = os.environ.copy()
    lib_path = str(plan.cwd / "lib")
    env["LD_LIBRARY_PATH"] = f"{lib_path}:{env.get('LD_LIBRARY_PATH', '')}"
    print(f"[INFO] Starting backend: {' '.join(plan.command)}")
    print(f"[INFO] Backend cwd: {plan.cwd}")
    return subprocess.Popen(
        plan.command,
        cwd=plan.cwd,
        env=env,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.STDOUT,
        start_new_session=True,
    )


def stop_backend(process: subprocess.Popen[str] | None, plan: BackendPlan | None) -> None:
    if plan is not None:
        print(f"[INFO] Stopping tmux session `{plan.session_name}`...")
        subprocess.run(["tmux", "kill-session", "-t", plan.session_name], check=False)
    if process is not None and process.poll() is None:
        print("[INFO] Terminating backend launcher process...")
        try:
            os.killpg(process.pid, signal.SIGTERM)
        except ProcessLookupError:
            pass
        try:
            process.wait(timeout=3.0)
        except subprocess.TimeoutExpired:
            os.killpg(process.pid, signal.SIGKILL)
            process.wait(timeout=3.0)


def robot_has_state(robot_interface: Any) -> bool:
    return bool(getattr(robot_interface, "state_buffer_size", 0))


def gripper_has_state(robot_interface: Any) -> bool:
    return bool(getattr(robot_interface, "gripper_state_buffer_size", 0))


def summarize_robot(name: str, robot_interface: Any) -> bool:
    print(f"\n[{name}]")
    print(f"state_buffer_size={robot_interface.state_buffer_size}")
    print(f"gripper_state_buffer_size={robot_interface.gripper_state_buffer_size}")

    if robot_has_state(robot_interface):
        state = robot_interface._state_buffer[-1]
        q = np.array(state.q)
        dq = np.array(state.dq)
        print("q=", np.round(q, 4).tolist())
        print("dq=", np.round(dq, 4).tolist())
        if len(state.O_T_EE) == 16:
            eef = np.array(state.O_T_EE).reshape(4, 4).T
            print("eef_pos=", np.round(eef[:3, 3], 4).tolist())
        print("robot_mode=", state.robot_mode)
        print("frame=", state.frame)
        print("control_command_success_rate=", state.control_command_success_rate)
    else:
        print("NO ARM STATE RECEIVED")

    if gripper_has_state(robot_interface):
        gripper_state = robot_interface._gripper_state_buffer[-1]
        print(
            "gripper_width=",
            round(gripper_state.width, 5),
            "is_grasped=",
            gripper_state.is_grasped,
            "temp=",
            gripper_state.temperature,
        )
    else:
        print("NO GRIPPER STATE RECEIVED")

    return robot_has_state(robot_interface)


def main() -> int:
    args = parse_args()
    if args.duration <= 0:
        print("[ERROR] --duration must be positive.", file=sys.stderr)
        return 2
    if args.interval <= 0:
        print("[ERROR] --interval must be positive.", file=sys.stderr)
        return 2
    if args.backend_wait < 0:
        print("[ERROR] --backend-wait must be non-negative.", file=sys.stderr)
        return 2

    try:
        backend_plan = build_backend_plan(args.start_backend, list(args.configs), args.tmux_session)
    except ValueError as exc:
        print(f"[ERROR] {exc}", file=sys.stderr)
        return 2

    backend_process = None
    robots: list[tuple[str, Any]] = []
    try:
        backend_process = start_backend(backend_plan)
        if backend_process is not None and args.backend_wait:
            print(f"[INFO] Waiting {args.backend_wait:.1f}s for backend startup...")
            time.sleep(args.backend_wait)
            if backend_process.poll() is not None:
                output = backend_process.stdout.read() if backend_process.stdout else ""
                print("[WARN] Backend launcher exited early.")
                if output.strip():
                    print(output.rstrip())

        FrankaInterface = import_franka_interface()
        for config in args.configs:
            cfg_path = resolve_config(config)
            if not cfg_path.exists():
                print(f"[ERROR] Missing config: {cfg_path}", file=sys.stderr)
                return 1
            name = Path(config).stem
            print(f"[INFO] Creating read-only interface for {name}: {cfg_path}")
            robot = FrankaInterface(
                str(cfg_path),
                use_visualizer=False,
                has_gripper=not args.no_gripper,
                automatic_gripper_reset=False,
            )
            assert_read_only_interface_usage(robot)
            robots.append((name, robot))

        deadline = time.monotonic() + args.duration
        next_report = 0.0
        while time.monotonic() < deadline:
            now = time.monotonic()
            if now >= next_report:
                status = ", ".join(
                    f"{name}: state={robot.state_buffer_size}, gripper={robot.gripper_state_buffer_size}"
                    for name, robot in robots
                )
                print(f"[WAIT] {status}")
                next_report = now + args.interval
            if robots and all(robot_has_state(robot) for _, robot in robots):
                break
            time.sleep(0.05)

        print("\n=== READ RESULT ===")
        successes = [summarize_robot(name, robot) for name, robot in robots]
        if any(successes):
            print("\n[PASS] Received Deoxys robot state data.")
            return 0
        print("\n[FAIL] Did not receive Deoxys robot state data within the requested duration.")
        print("       Check whether auto_bimanual/franka-interface is running and ports match configs.")
        return 1
    except KeyboardInterrupt:
        print("\n[INFO] Interrupted by user.")
        return 130
    except Exception as exc:  # noqa: BLE001 - diagnostic should surface hardware/env failures.
        print(f"[ERROR] Deoxys diagnostic failed: {exc}", file=sys.stderr)
        return 1
    finally:
        for _, robot in robots:
            try:
                robot.close()
            except Exception:
                pass
        stop_backend(backend_process, backend_plan)


if __name__ == "__main__":
    raise SystemExit(main())
